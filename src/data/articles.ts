/**
 * Returns only content-audited educational articles approved for public listing.
 */
export function getPublishedArticles(): ArticleItem[] {
  return articlesData.filter((article) => article.publicationStatus === "published");
}

/**
 * Returns an article by slug, checking both published and pending for detail routing.
 */
export function getArticleBySlug(slug: string): ArticleItem | undefined {
  return articlesData.find((article) => article.slug === slug);
}

/**
 * Returns related published articles excluding the current slug.
 */
export function getRelatedArticles(currentSlug: string, limit = 2): ArticleItem[] {
  return getPublishedArticles()
    .filter((article) => article.slug !== currentSlug)
    .slice(0, limit);
}

/**
 * Returns all unique categories from published articles.
 */
export function getAllArticleCategories(): string[] {
  const published = getPublishedArticles();
  const categories = Array.from(new Set(published.map((a) => a.category)));
  return ["All", ...categories];
}
